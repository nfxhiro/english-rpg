function katakanaToHiragana(value: string) {
  return value.replace(/[\u30a1-\u30f6]/g, (char) =>
    String.fromCharCode(char.charCodeAt(0) - 0x60)
  );
}

export function getEiken4Reading(meaning: string): string | undefined {
  return eiken4Readings[meaning];
}

export const eiken4Readings: Record<string, string> =
  eiken4RawWords.reduce<Record<string, string>>((readings, word) => {
    readings[word.meaning] =
      eiken4ExactReadings[word.meaning] ?? katakanaToHiragana(word.meaning);
    return readings;
  }, {});
