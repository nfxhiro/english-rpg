function katakanaToHiragana(value: string) {
  return value.replace(/[\u30a1-\u30f6]/g, (char) =>
    String.fromCharCode(char.charCodeAt(0) - 0x60)
  );
}

function applyTermReadings(value: string) {
  const entries = Object.entries(eiken3ReadingTerms).sort(
    ([left], [right]) => right.length - left.length
  );

  return entries.reduce((text, [source, reading]) => {
    return text.split(source).join(reading);
  }, value);
}

function applyFallbackKanjiReadings(value: string) {
  return value.replace(/[一-龯々〆ヵヶ]/g, (char) => {
    return fallbackKanjiReadings[char] ?? char;
  });
}

function createEiken3Reading(meaning: string) {
  const knownReading = getEiken5Reading(meaning) ?? getEiken4Reading(meaning);
  if (knownReading) return knownReading;

  return applyFallbackKanjiReadings(
    applyTermReadings(katakanaToHiragana(meaning))
  );
}

export function getEiken3Reading(meaning: string): string | undefined {
  return eiken3Readings[meaning];
}

export const eiken3Readings: Record<string, string> =
  eiken3RawWords.reduce<Record<string, string>>((readings, word) => {
    readings[word.meaning] = createEiken3Reading(word.meaning);
    return readings;
  }, {});
