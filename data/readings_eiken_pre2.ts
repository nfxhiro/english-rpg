function katakanaToHiragana(value: string) {
  return value.replace(/[\u30a1-\u30f6]/g, (char) =>
    String.fromCharCode(char.charCodeAt(0) - 0x60)
  );
}

function createEikenPre2Reading(meaning: string) {
  return (
    eikenPre2ExactReadings[meaning] ??
    getEiken3Reading(meaning) ??
    katakanaToHiragana(meaning)
  );
}

export function getEikenPre2Reading(meaning: string): string | undefined {
  return eikenPre2Readings[meaning];
}

export const eikenPre2Readings: Record<string, string> =
  eikenPre2RawWords.reduce<Record<string, string>>((readings, word) => {
    readings[word.meaning] = createEikenPre2Reading(word.meaning);
    return readings;
  }, {});
